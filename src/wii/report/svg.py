"""Hand-rolled SVG charts — no JS, no CDN, no build step.

The report must open from a `file://` path on a plane with no network, so every
pixel here is generated by this file. Roughly 300 lines of string building buys
us a report that is a single self-contained HTML file and will still render in
ten years.
"""

from __future__ import annotations

import html
from typing import Any, Dict, List, Sequence, Tuple

from .. import config

FONT = "'Segoe UI','Microsoft YaHei',-apple-system,BlinkMacSystemFont,'Helvetica Neue',Arial,sans-serif"
INK = "#1f2328"
MUTED = "#6b7280"
GRID = "#e6e8eb"
PAPER = "#ffffff"

VAL_NEG = "#3d5a80"
VAL_MID = "#9aa0a6"
VAL_POS = "#d97742"


def esc(text: Any) -> str:
    return html.escape(str(text), quote=True)


def _hex_to_rgb(h: str) -> Tuple[int, int, int]:
    h = h.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def _mix(c1: str, c2: str, t: float) -> str:
    t = max(0.0, min(1.0, t))
    r1, g1, b1 = _hex_to_rgb(c1)
    r2, g2, b2 = _hex_to_rgb(c2)
    return "#%02x%02x%02x" % (
        round(r1 + (r2 - r1) * t),
        round(g1 + (g2 - g1) * t),
        round(b1 + (b2 - b1) * t),
    )


def valence_color(v: float) -> str:
    return _mix(VAL_NEG, VAL_MID, 1 + v) if v < 0 else _mix(VAL_POS, VAL_MID, 1 - v)


def heat_color(t: float, base: str = "#2f4858") -> str:
    """White -> factor colour, for the percentile heat table."""
    return _mix("#ffffff", base, 0.08 + 0.62 * max(0.0, min(1.0, t)))


def _svg_open(width: int, height: int, label: str) -> List[str]:
    return [
        f'<svg class="chart" viewBox="0 0 {width} {height}" width="100%" '
        f'preserveAspectRatio="xMidYMid meet" role="img" aria-label="{esc(label)}" '
        f'xmlns="http://www.w3.org/2000/svg" style="font-family:{FONT}">',
        f'<rect x="0" y="0" width="{width}" height="{height}" fill="{PAPER}"/>',
    ]


# ---------------------------------------------------------------------------
# Chart 1: magnitude x valence scatter
# ---------------------------------------------------------------------------
def scatter(artists: Sequence[Any], width: int = 1000, height: int = 460) -> str:
    left, right, top, bottom = 74, 40, 34, 64
    pw, ph = width - left - right, height - top - bottom
    out = _svg_open(width, height, "影响幅度 × 情感极性散点图")

    def sx(star: float) -> float:
        return left + (star - config.STAR_MIN) / (config.STAR_MAX - config.STAR_MIN) * pw

    def sy(val: float) -> float:
        return top + (1.0 - (val + 1.0) / 2.0) * ph

    # neutral band
    band_top, band_bot = sy(config.VALENCE_NEUTRAL_BAND), sy(-config.VALENCE_NEUTRAL_BAND)
    out.append(
        f'<rect x="{left}" y="{band_top:.1f}" width="{pw}" height="{band_bot - band_top:.1f}" '
        f'fill="#f3f4f6"/>'
    )
    out.append(
        f'<text x="{left + pw - 6}" y="{band_top - 6:.1f}" text-anchor="end" font-size="11" '
        f'fill="{MUTED}">中性带 |极性| &lt; {config.VALENCE_NEUTRAL_BAND}</text>'
    )

    # grid
    for s in range(int(config.STAR_MIN), int(config.STAR_MAX) + 1):
        x = sx(s)
        out.append(f'<line x1="{x:.1f}" y1="{top}" x2="{x:.1f}" y2="{top + ph}" stroke="{GRID}"/>')
        out.append(
            f'<text x="{x:.1f}" y="{top + ph + 20}" text-anchor="middle" font-size="12" '
            f'fill="{MUTED}">{s}</text>'
        )
    for v in (-1.0, -0.5, 0.0, 0.5, 1.0):
        y = sy(v)
        stroke = "#cfd3d8" if v == 0 else GRID
        out.append(f'<line x1="{left}" y1="{y:.1f}" x2="{left + pw}" y2="{y:.1f}" stroke="{stroke}"/>')
        out.append(
            f'<text x="{left - 10}" y="{y + 4:.1f}" text-anchor="end" font-size="12" fill="{MUTED}">'
            f'{v:+.1f}</text>'
        )

    out.append(
        f'<text x="{left + pw / 2:.1f}" y="{height - 14}" text-anchor="middle" font-size="12.5" '
        f'fill="{INK}">影响幅度 →（星级，1-10）</text>'
    )
    out.append(
        f'<text x="18" y="{top + ph / 2:.1f}" text-anchor="middle" font-size="12.5" fill="{INK}" '
        f'transform="rotate(-90 18 {top + ph / 2:.1f})">情感极性 →（-1 负 / +1 正）</text>'
    )

    # points, biggest bubble first so small ones stay clickable-looking
    ordered = sorted(artists, key=lambda a: -a.normalized["reach"])
    for a in reversed(ordered):
        r = 7 + 13 * a.normalized["reach"]
        x, y = sx(a.stars), sy(a.valence)
        out.append(
            f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r:.1f}" '
            f'fill="{valence_color(a.valence)}" fill-opacity="0.82" '
            f'stroke="#ffffff" stroke-width="1.6"><title>{esc(a.name)}：{a.stars:.1f} 星 / '
            f'极性 {a.valence:+.2f} / 触达百分位 {a.normalized["reach"]:.2f}</title></circle>'
        )

    placed: List[Tuple[float, float, float, float]] = []
    for a in ordered:
        r = 7 + 13 * a.normalized["reach"]
        x, y = sx(a.stars), sy(a.valence)
        label = f"{a.name} {a.stars:.1f}★"
        w = len(label) * 12.4 + 6
        h = 16.0
        candidates = [
            (x + r + 6, y + 4.5, "start"),
            (x - r - 6, y + 4.5, "end"),
            (x, y - r - 8, "middle"),
            (x, y + r + 16, "middle"),
        ]
        chosen = candidates[0]
        for cx, cy, anchor in candidates:
            bx = cx if anchor == "start" else cx - w if anchor == "end" else cx - w / 2
            box = (bx, cy - h + 3, bx + w, cy + 4)
            inside = left - 4 <= box[0] and box[2] <= left + pw + 4
            clash = any(
                not (box[2] < p[0] or box[0] > p[2] or box[3] < p[1] or box[1] > p[3])
                for p in placed
            )
            if inside and not clash:
                chosen = (cx, cy, anchor)
                break
        placed.append((chosen[0] - w if chosen[2] == "end" else chosen[0], chosen[1] - 12, chosen[0], chosen[1] + 4))
        out.append(
            f'<text x="{chosen[0]:.1f}" y="{chosen[1]:.1f}" text-anchor="{chosen[2]}" '
            f'font-size="12" fill="{INK}">{esc(label)}</text>'
        )

    out.append("</svg>")
    return "\n".join(out)


# ---------------------------------------------------------------------------
# Chart 2: contribution stacked bars
# ---------------------------------------------------------------------------
def stacked_contributions(artists: Sequence[Any], weights: Dict[str, float], width: int = 1000) -> str:
    row_h, gap = 26, 12
    header_h = 34
    height = header_h + len(artists) * (row_h + gap) + 26
    name_w = 104
    bar_x0, bar_x1 = name_w + 12, width - 116
    bar_w = bar_x1 - bar_x0
    out = _svg_open(width, height, "六因子贡献分解")

    out.append(
        f'<text x="{bar_x0}" y="16" font-size="11.5" fill="{MUTED}">'
        f'条形长度 = 合成幅度 M = Σ 权重 × 归一值；末端数字 = 星级 = 1 + 9M</text>'
    )

    for i, a in enumerate(artists):
        y = header_h + i * (row_h + gap)
        out.append(
            f'<text x="{name_w}" y="{y + 17}" text-anchor="end" font-size="13" fill="{INK}">'
            f'{esc(a.name)}</text>'
        )
        x = bar_x0
        for factor in config.FACTORS:
            seg = a.contribution[factor] * bar_w
            if seg <= 0:
                continue
            out.append(
                f'<rect x="{x:.2f}" y="{y}" width="{max(seg, 0.6):.2f}" height="{row_h}" '
                f'fill="{config.FACTOR_META[factor]["color"]}"><title>{esc(config.FACTOR_META[factor]["zh"])}'
                f'：贡献 {a.contribution[factor]:.3f}（权重 {weights[factor]:.2f} × 归一 '
                f'{a.normalized[factor]:.2f}）</title></rect>'
            )
            x += seg
        out.append(
            f'<rect x="{bar_x0}" y="{y}" width="{bar_w}" height="{row_h}" fill="none" stroke="{GRID}"/>'
        )
        out.append(
            f'<text x="{bar_x1 + 10}" y="{y + 17}" font-size="12.5" fill="{INK}">'
            f'<tspan font-weight="600">{a.stars:.1f}</tspan> 星</text>'
        )
        out.append(
            f'<text x="{bar_x1 + 58}" y="{y + 17}" font-size="11.5" '
            f'fill="{valence_color(a.valence)}">{a.valence:+.2f}</text>'
        )

    # legend
    ly = height - 12
    lx = bar_x0
    for factor in config.FACTORS:
        meta = config.FACTOR_META[factor]
        out.append(f'<rect x="{lx}" y="{ly - 9}" width="11" height="11" rx="2" fill="{meta["color"]}"/>')
        out.append(
            f'<text x="{lx + 15}" y="{ly}" font-size="11.5" fill="{MUTED}">{esc(meta["zh"])} '
            f'{weights[factor]:.2f}</text>'
        )
        lx += 28 + (len(meta["zh"]) * 11.5 + 34)
    out.append("</svg>")
    return "\n".join(out)


# ---------------------------------------------------------------------------
# Chart 3: per-artist event timeline (embedded inside <details>)
# ---------------------------------------------------------------------------
def mini_timeline(
    events: Sequence[Dict[str, Any]],
    window_start: Any,
    window_end: Any,
    width: int = 900,
    height: int = 118,
) -> str:
    left, right = 24, 24
    axis_y = height // 2
    pw = width - left - right
    out = _svg_open(width, height, "已核实事件时间线")
    if not window_start or not window_end:
        out.append(f'<text x="{width/2}" y="{axis_y}" text-anchor="middle" font-size="12" fill="{MUTED}">'
                   f'无时间窗数据</text></svg>')
        return "\n".join(out)

    span = max(1, (window_end - window_start).days)

    def sx(d) -> float:
        return left + (d - window_start).days / span * pw

    out.append(f'<line x1="{left}" y1="{axis_y}" x2="{left + pw}" y2="{axis_y}" stroke="#cfd3d8"/>')
    for d, label in ((window_start, window_start.isoformat()), (window_end, window_end.isoformat())):
        out.append(f'<circle cx="{sx(d):.1f}" cy="{axis_y}" r="2.5" fill="{MUTED}"/>')
        out.append(
            f'<text x="{sx(d):.1f}" y="{axis_y + 20}" text-anchor="middle" font-size="10.5" '
            f'fill="{MUTED}">{label}</text>'
        )

    if not events:
        out.append(f'<text x="{width/2}" y="{axis_y - 12}" text-anchor="middle" font-size="12" '
                   f'fill="{MUTED}">该窗口内无已核实事件（舆论提及不等于事实，故不画点）</text>')
        out.append("</svg>")
        return "\n".join(out)

    for i, ev in enumerate(events):
        x = sx(ev["date"]) if not isinstance(ev["date"], str) else sx(_to_date(ev["date"]))
        up = i % 2 == 0
        stem = 18 if up else -18
        color = "#b23a48" if ev.get("event_type") in ("endorsement_terminated", "allegation", "legal",
                                                     "production_cancelled") else "#2f4858"
        out.append(f'<line x1="{x:.1f}" y1="{axis_y}" x2="{x:.1f}" y2="{axis_y - stem}" stroke="{color}"/>')
        out.append(f'<circle cx="{x:.1f}" cy="{axis_y}" r="4.5" fill="{color}"/>')
        ty = axis_y - stem - 6 if up else axis_y - stem + 12
        anchor = "middle"
        if x < left + 80:
            anchor = "start"
        elif x > left + pw - 80:
            anchor = "end"
        out.append(
            f'<text x="{x:.1f}" y="{ty:.1f}" text-anchor="{anchor}" font-size="11" fill="{INK}">'
            f'{esc(ev["title"][:26])}</text>'
        )
        out.append(
            f'<text x="{x:.1f}" y="{ty + 13:.1f}" text-anchor="{anchor}" font-size="10" fill="{MUTED}">'
            f'{ev["date"]} · {esc(ev["event_type"])}</text>'
        )
    out.append("</svg>")
    return "\n".join(out)


def _to_date(value: str):
    import datetime as _dt

    return _dt.date.fromisoformat(value[:10])


# ---------------------------------------------------------------------------
# Heat table (plain HTML, colour-coded)
# ---------------------------------------------------------------------------
def heat_table(artists: Sequence[Any]) -> str:
    cols = "".join(f"<th>{esc(config.FACTOR_META[f]['zh'])}</th>" for f in config.FACTORS)
    rows = []
    for a in artists:
        cells = []
        for f in config.FACTORS:
            n = a.normalized[f]
            cells.append(
                f"<td style=\"background:{heat_color(n, config.FACTOR_META[f]['color'])}\" "
                f"title=\"{esc(config.FACTOR_META[f]['zh'])} 归一值 {n:.3f}\">{n:.2f}</td>"
            )
        rows.append(
            f"<tr><th class='row'>{esc(a.name)}</th><th class='row num'>{a.stars:.1f}★</th>"
            + "".join(cells)
            + "</tr>"
        )
    return (
        f"<table class='heat'><thead><tr><th>艺人</th><th>星级</th>{cols}</tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table>"
    )
